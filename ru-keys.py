#!/usr/bin/env python3
"""Regenerate config.yml keybindings with Russian-layout aliases from `lazygit --config`."""
import subprocess
from pathlib import Path

import yaml

EN = "`qwertyuiop[]asdfghjkl;'zxcvbnm,.~QWERTYUIOP{}ASDFGHJKL:\"ZXCVBNM<>#"
RU = "ёйцукенгшщзхъфывапролджэячсмитьбюЁЙЦУКЕНГШЩЗХЪФЫВАПРОЛДЖЭЯЧСМИТЬБЮ№"
TO_RU = dict(zip(EN, RU))


def aliased(keys):
    out = list(keys)
    for key in keys:
        if key in TO_RU and TO_RU[key] not in out:
            out.append(TO_RU[key])
    return out


def walk(node):
    result = {}
    for name, value in node.items():
        if isinstance(value, dict):
            sub = walk(value)
            if sub:
                result[name] = sub
        else:
            keys = value if isinstance(value, list) else [value]
            keys = [k for k in keys if isinstance(k, str)]
            new = aliased(keys)
            if new != keys:
                result[name] = new
    return result


defaults = yaml.load(subprocess.run(["lazygit", "--config"], capture_output=True, text=True, check=True).stdout, Loader=yaml.BaseLoader)
config_path = Path(__file__).with_name("config.yml")
config = yaml.safe_load(config_path.read_text()) or {} if config_path.exists() else {}
config["keybinding"] = walk(defaults["keybinding"])
config_path.write_text(
    "# keybinding section is generated by ru-keys.py; rerun it after upgrading lazygit\n"
    + yaml.safe_dump(config, allow_unicode=True, sort_keys=False)
)
